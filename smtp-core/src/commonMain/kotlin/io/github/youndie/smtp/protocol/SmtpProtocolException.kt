package io.github.youndie.smtp.protocol

/**
 * Сервер прислал то, что протоколом не предусмотрено: неразбираемый ответ, слишком длинную строку,
 * разные коды в строках одного ответа.
 *
 * Это не отказ сервера — отказ приезжает нормальным ответом с кодом 4xx или 5xx и разбирается
 * без исключений. Классификация отказов появится на M-26.
 */
public class SmtpProtocolException(
    message: String,
) : RuntimeException(message)
